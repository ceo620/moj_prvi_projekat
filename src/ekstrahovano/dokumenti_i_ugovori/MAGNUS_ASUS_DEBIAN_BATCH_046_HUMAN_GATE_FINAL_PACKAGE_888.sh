{
echo "PROTOCOL=888"
echo "MACHINE=ASUS"
echo "NODE=FREYA_ASUS_DEBIAN_888"
echo "BATCH=046"
echo "MODE=READ_ONLY_HUMAN_GATE_FINAL_PACKAGE"
