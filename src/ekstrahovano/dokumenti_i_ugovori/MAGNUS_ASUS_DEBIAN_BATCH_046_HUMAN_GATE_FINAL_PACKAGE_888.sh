-maxdepth 2 \
-type f \
\( \
-name "SUMMARY.env" -o \
-name "BATCH.env" -o \
-name "CERTIFICATION_STATUS.txt" -o \
-name "GOVERNANCE_STATUS.txt" -o \
-name "HUMAN_GATE_FINAL_REVIEW.txt" \
