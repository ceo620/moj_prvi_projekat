  echo "MOVE_ALLOWED=NO"
  echo "RENAME_ALLOWED=NO"
  echo "PURGE_ALLOWED=NO"
  echo "WEB_SERVER_ALLOWED=NO"
  echo "NETWORK_HARVESTER_ALLOWED=NO"
  echo "SUBPROCESS_ORCHESTRATOR_ALLOWED=NO"
  echo "ORIGINALS_CHANGED=NO"

  run_latest "SAFE_STATUS_CENTER" "$ROOT/22_ANDROID_SAFE_REVIVAL_PLAN/SAFE_STATUS_COMMAND_CENTER" "SAFE_STATUS_COMMAND_CENTER_STEP_116_*.sh"

  run_latest "REPORT_ONLY_SAFE_LAUNCH" "$ROOT/22_ANDROID_SAFE_REVIVAL_PLAN/REPORT_ONLY_EXECUTABLES" "REPORT_ONLY_SAFE_LAUNCH_CANDIDATES_STEP_117_*.sh"

