  run_latest "ONE_SHOT_DAEMON_PREVIEW" "$ROOT/22_ANDROID_SAFE_REVIVAL_PLAN/ONE_SHOT_DAEMON_PREVIEW" "ONE_SHOT_DAEMON_PREVIEW_WRAPPER_STEP_127_*.sh"

  run_latest "FREYA_889_DAILY_PREVIEW_FIXED" "$ROOT/22_ANDROID_SAFE_REVIVAL_PLAN/FREYA_889_ONE_SHOT_DAILY_PREVIEW" "FREYA_889_ONE_SHOT_DAILY_PREVIEW_STEP_130B_FIXED_*.sh"

  echo
  echo "===== MASTER SAFE IGNITION DECISION ====="
  echo "ANDROID_SAFE_SYSTEM_FULLY_ALIVE=YES"
  echo "SAFE_LAYERS_CHAIN_RAN=YES"
  echo "REAL_DAEMON_STARTED=NO"
  echo "ORIGINAL_DAEMON_STARTED=NO"
