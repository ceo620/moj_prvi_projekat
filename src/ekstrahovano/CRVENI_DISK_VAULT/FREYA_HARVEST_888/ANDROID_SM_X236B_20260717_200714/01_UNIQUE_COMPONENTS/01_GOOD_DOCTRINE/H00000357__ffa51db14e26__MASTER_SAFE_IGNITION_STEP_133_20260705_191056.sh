#!/data/data/com.termux/files/usr/bin/bash
set -u

ROOT="/data/data/com.termux/files/home/FREYA_ANDROID_TABLET_FORENSIC_REVIVAL_20260705_150231"
OUT="$ROOT/22_ANDROID_SAFE_REVIVAL_PLAN/MASTER_SAFE_IGNITION/RUN_OUTPUT"
TS="$(date +%Y%m%d_%H%M%S)"
mkdir -p "$OUT"

REPORT="$OUT/MASTER_SAFE_IGNITION_REPORT_$TS.txt"

run_latest() {
  LABEL="$1"
  DIR="$2"
  PATTERN="$3"

  TARGET="$(find "$DIR" -type f -name "$PATTERN" 2>/dev/null | sort | tail -1)"
  echo
  echo "===== RUN $LABEL ====="
  echo "TARGET=$TARGET"

  if [ -n "$TARGET" ] && [ -f "$TARGET" ]; then
    bash "$TARGET"
  else
    echo "${LABEL}_TARGET_NOT_FOUND"
  fi
}

{
  echo "===== MASTER SAFE IGNITION — PROTOKOL 889 ====="
  echo "HUMAN_GATE=ACTIVE"
  echo "MODE=FULL_SAFE_SYSTEM_IGNITION"
  echo "FULL_RISK_RUNTIME=NO"
  echo "ORIGINAL_DAEMONS=NO"
